"""Summarize results/grades.csv: how often each grader (and each stack of graders) rewards a buggy design or rejects a
correct one, where the two simulators disagree, and which bugs survive. Deterministic outputs:
results/report.md, figures/grader_matrix.svg, figures/reward_errors.svg. Machine-dependent (from results/timing.csv,
not compared by `make check`): figures/grader_seconds.svg.

usage: python3 -m rrb.report
"""
import csv
import html
import json
import os
import statistics
import subprocess
import sys

from .graders import GRADERS
from .tasks import ROOT, load_task

RESULTS = os.path.join(ROOT, "results")
FIGURES = os.path.join(ROOT, "figures")

# a stack rewards a design only if every grader in it passes; "n/a" (grader not defined for the task) counts as pass
STACKS = [
    ("compile only", ["compile"]),
    ("weak testbench", ["weak"]),
    ("lint", ["lint"]),
    ("strong TB, Icarus", ["strong_icarus"]),
    ("strong TB, Verilator", ["strong_verilator"]),
    ("strong TB, both simulators", ["strong_icarus", "strong_verilator"]),
    ("formal alone", ["formal"]),
    ("both simulators + formal", ["strong_icarus", "strong_verilator", "formal"]),
    ("full stack", ["compile", "strong_icarus", "strong_verilator", "formal", "synth", "timed"]),
]
SHORT = {"weak testbench": "weak TB", "lint": "lint", "strong TB, Icarus": "strong, Icarus",
         "strong TB, Verilator": "strong, Verilator", "strong TB, both simulators": "strong, both",
         "formal alone": "formal", "both simulators + formal": "strong + formal", "full stack": "full stack"}
COLORS = {"pass": "#2da44e", "fail": "#cf222e", "error": "#82071e", "n/a": "#d0d7de"}


def load():
    grades = {}
    for r in csv.DictReader(open(os.path.join(RESULTS, "grades.csv"))):
        key = (r["task"], r["candidate"])
        g = grades.setdefault(key, {"task": r["task"], "candidate": r["candidate"], "label": r["label"],
                                    "class": r["class"], "v": {}})
        g["v"][r["grader"]] = r["verdict"]
    rows = sorted(grades.values(), key=lambda g: (g["task"], g["candidate"] != "golden", g["label"] != "correct",
                                                  g["candidate"]))
    return rows


def rewarded(row, graders):
    return all(row["v"].get(g) in ("pass", "n/a") for g in graders)


def stack_table(rows):
    bugs = [r for r in rows if r["label"] == "bug"]
    good = [r for r in rows if r["label"] == "correct"]
    out = []
    for name, gs in STACKS:
        # graders that are n/a for a task are left out of that task's stack; a stack made only of n/a graders
        # does not grade the task at all, so those candidates are left out of its counts
        def applies(r):
            return any(r["v"].get(g) != "n/a" for g in gs)
        b = [r for r in bugs if applies(r)]
        c = [r for r in good if applies(r)]
        fp = [r for r in b if rewarded(r, gs)]
        ff = [r for r in c if not rewarded(r, gs)]
        out.append((name, gs, len(b), len(fp), len(c), len(ff), fp, ff))
    return out


def pct(a, b):
    return f"{100 * a / b:.0f} %" if b else "-"


def report_md(rows, table):
    tasks = sorted({r["task"] for r in rows})
    nb = sum(r["label"] == "bug" for r in rows)
    nc = sum(r["label"] == "correct" for r in rows)
    L = ["# Grader report", "",
         f"Generated by `python3 -m rrb.report` from `results/grades.csv`: {len(tasks)} tasks, {nc} correct designs "
         f"(golden designs included) and {nb} buggy designs.", "",
         "## Reward errors by grader stack", "",
         "A stack gives reward 1 only if every grader in it passes. **Bugs rewarded** is the false-pass rate (what a "
         "policy could exploit); **correct rejected** is the false-fail rate (signal lost on good designs).", "",
         "| Stack | Bugs rewarded | Correct rejected |", "|---|---|---|"]
    for name, gs, b, fp, c, ff, _, _ in table:
        L.append(f"| {name} | {fp} of {b} ({pct(fp, b)}) | {ff} of {c} ({pct(ff, c)}) |")
    L += ["", "## Bugs each stack misses", ""]
    for name, gs, b, fp, c, ff, fps, ffs in table:
        if name in ("compile only",):
            continue
        L.append(f"**{name}**: " + (", ".join(f"`{r['task']}/{r['candidate']}`" for r in fps) or "none"))
        L.append("")
    L += ["## Correct designs rejected", ""]
    for name, gs, b, fp, c, ff, fps, ffs in table:
        if ffs:
            L.append(f"**{name}**: " + ", ".join(f"`{r['task']}/{r['candidate']}`" for r in ffs))
            L.append("")
    dis = [r for r in rows if r["v"]["strong_icarus"] != r["v"]["strong_verilator"]]
    L += ["## Simulator disagreements", "",
          "The same strong testbench and design, different verdicts from Icarus and Verilator:", ""]
    L += [f"* `{r['task']}/{r['candidate']}` ({r['label']}): Icarus {r['v']['strong_icarus']}, "
          f"Verilator {r['v']['strong_verilator']}" for r in dis] or ["* none"]
    L += ["", "## Designs", "", "What every design does wrong (bugs) or differently (correct alternatives), from the "
          "header comments of the design files.", ""]
    for tid in tasks:
        t = load_task(tid)
        L += [f"### {tid}: {t['title']}", "", f"Origin: {t.get('origin', '')}.", ""]
        for c in t["candidates"]:
            kind = f"bug, {c['class']}" if c["label"] == "bug" else "correct"
            L.append(f"* `{c['name']}` ({kind}): {c['note']}")
        L.append("")
    L += ["## Every verdict", "", "| Task | Design | Label | " + " | ".join(GRADERS) + " |",
          "|---|---|---|" + "---|" * len(GRADERS)]
    for r in rows:
        L.append(f"| {r['task']} | {r['candidate']} | {r['label']} | " +
                 " | ".join(r["v"].get(g, "") for g in GRADERS) + " |")
    with open(os.path.join(RESULTS, "report.md"), "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")


def matrix_svg(rows):
    cw, rh, lw, top = 92, 16, 375, 70
    W = lw + cw * len(GRADERS) + 20
    H = top + rh * len(rows) + 50
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
         f'font-family="DejaVu Sans, Arial, sans-serif" font-size="11">',
         f'<rect width="{W}" height="{H}" fill="#ffffff"/>',
         '<text x="12" y="22" font-size="15" font-weight="bold" fill="#1f2328">Every grader on every design</text>',
         '<text x="12" y="40" fill="#57606a">rows: designs (red name = known bug). Green: the grader passes the design, '
         'so green on a red row is a false pass</text>']
    for j, g in enumerate(GRADERS):
        o.append(f'<text x="{lw + cw * j + cw / 2}" y="{top - 8}" text-anchor="middle" fill="#1f2328">{g}</text>')
    prev = None
    for i, r in enumerate(rows):
        y = top + rh * i
        if r["task"] != prev:
            o.append(f'<line x1="8" y1="{y}" x2="{W - 12}" y2="{y}" stroke="#8c959f"/>')
            o.append(f'<text x="12" y="{y + 12}" font-weight="bold" fill="#1f2328">{r["task"]}</text>')
            prev = r["task"]
        col = "#cf222e" if r["label"] == "bug" else "#1f2328"
        o.append(f'<text x="165" y="{y + 12}" fill="{col}">{html.escape(r["candidate"])}</text>')
        for j, g in enumerate(GRADERS):
            v = r["v"].get(g, "n/a")
            o.append(f'<rect x="{lw + cw * j + 2}" y="{y + 2}" width="{cw - 4}" height="{rh - 3}" '
                     f'fill="{COLORS[v]}"><title>{r["task"]}/{r["candidate"]} {g}: {v}</title></rect>')
    y = top + rh * len(rows) + 22
    for k, (v, c) in enumerate(COLORS.items()):
        o.append(f'<rect x="{12 + 90 * k}" y="{y - 10}" width="12" height="12" fill="{c}"/>')
        o.append(f'<text x="{30 + 90 * k}" y="{y}" fill="#1f2328">{v}</text>')
    o.append("</svg>")
    with open(os.path.join(FIGURES, "grader_matrix.svg"), "w", newline="\n") as f:
        f.write("\n".join(o) + "\n")


def chart(spec, name):
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    sp = os.path.join(ROOT, "build", name + ".json")
    json.dump(spec, open(sp, "w"))
    subprocess.run([sys.executable, os.path.join(ROOT, "tools", "svgchart.py"), sp,
                    os.path.join(FIGURES, name + ".svg")], check=True)


def errors_svg(table):
    keep = [t for t in table if t[0] != "compile only"]
    chart({"kind": "bar", "title": "Reward errors of each grader stack", "ylabel": "percent of designs",
           "width": 980, "height": 440, "ymax": 100,
           "categories": [SHORT[t[0]] for t in keep],
           "series": [{"name": "bugs rewarded (false pass)", "y": [round(100 * t[3] / t[2], 1) for t in keep]},
                      {"name": "correct designs rejected (false fail)",
                       "y": [round(100 * t[5] / t[4], 1) for t in keep], "color": "#bf8700"}],
           "note": "full stack = compile + strong TB on both simulators + formal + synth rules + timed netlist"},
          "reward_errors")


def seconds_svg():
    secs = {}
    for r in csv.DictReader(open(os.path.join(RESULTS, "timing.csv"))):
        if float(r["seconds"]) > 0:
            secs.setdefault(r["grader"], []).append(float(r["seconds"]))
    gs = [g for g in GRADERS if g in secs]
    chart({"kind": "bar", "title": "Grader latency per design (median, this machine)", "ylabel": "seconds",
           "logy": True, "ymin": 0.01, "width": 760, "categories": gs,
           "series": [{"name": "median seconds", "y": [round(statistics.median(secs[g]), 3) for g in gs]}],
           "note": "machine-dependent; not compared by make check"}, "grader_seconds")


def main():
    os.makedirs(FIGURES, exist_ok=True)
    rows = load()
    for r in rows:                                     # every task named in the results must still exist
        load_task(r["task"])
    table = stack_table(rows)
    report_md(rows, table)
    matrix_svg(rows)
    errors_svg(table)
    if os.path.exists(os.path.join(RESULTS, "timing.csv")):
        seconds_svg()
    for name, gs, b, fp, c, ff, _, _ in table:
        print(f"{name:28s} bugs rewarded {fp:2d}/{b:2d}   correct rejected {ff:2d}/{c:2d}")


if __name__ == "__main__":
    main()
